export function generatedDocuments() {
  const { randomComparator, uniform, varied } = shuffleComparison();
  const queues = [randomComparator, uniform, varied];
  const checkout = checkoutOutcome();
  const result = new Map();
  for (const locale of Object.keys(locales)) {
    const home = readmePath(locale);
    result.set(home, readme(locale, home, queues, checkout).join('\n\n') + '\n');
  }
  result.set(contributionPath, contributionGuide().join('\n\n') + '\n');
  return result;
}

