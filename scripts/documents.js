function guideDirectory(locale, from) {
  const { headings, nav } = locales[locale];
  const { directory, categoryLabels, standardLabels } = productByLocale[locale];
  const copy = readDirectoryCopy(locale, records);
  const groups = categories.map(id => {
    const entries = recordsByCategory.get(id);
    if (!entries?.length || !categoryLabels[id]) throw new Error(locale + ': incomplete Directory category ' + id);
    return { id, entries, label: categoryLabels[id] + ' (' + entries.length + ')' };
  });
  const navigation = groups.map(({ id, label }) => [label, '#category-' + id]);
  const standardHeading = headings.standards + ' (' + standards.length + ')';
  navigation.push([standardHeading, '#engineering-standards']);
  return [
    sectionHeading(nav.directory, readmeAnchor(locale, 'directory')),
    directory,
    directoryCounts(locale).join(' · '),
    inlineNav(from, navigation),
    ...groups.flatMap(({ id, label, entries }) => [
      '<a id="category-' + id + '"></a>',
      details(label, [entries.map(record => {
        const { title, problem } = copy.get(record.id);
        return '- ' + link(title, from, recordPath(record)) + ' — ' + problem;
      }).join('\n')]),
    ]),
    sectionHeading(standardHeading, '#engineering-standards', 3),
    standards.map(({ id, path }) => {
      if (!standardLabels[id]) throw new Error(locale + ': missing Directory title for standard ' + id);
      return '- ' + link(standardLabels[id], from, 'skills/seniormode/' + path);
    }).join('\n'),
    link('Agent Skill', from, 'skills/seniormode/SKILL.md') + ' · ' +
      link(headings.library, from, 'skills/seniormode/references/catalog/index.md'),
  ];
}

