function checkoutOutcome() {
  const db = new DatabaseSync(':memory:');
  try {
    const charge = openTestProcessor(db);
    const request = { account: 'buyer', intent: 'purchase-42', cents: 1250 };
    assert.throws(() => charge(request, { loseResponse: true }), /Response lost/);
    const { status } = charge(request);
    const { total } = db.prepare('SELECT count(*) AS total FROM charges').get();
    assert.equal(status, 200);
    assert.equal(total, 1);
    return { status, total };
  } finally {
    db.close();
  }
}

