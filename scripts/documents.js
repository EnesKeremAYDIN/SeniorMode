function relative(from, path) {
  if (path.startsWith('https://') || path.startsWith('#')) return path;
  const [file, fragment] = path.split('#');
  return posix.relative(posix.dirname(from), file) + (fragment ? '#' + fragment : '');
}

function link(label, from, path, html = false) {
  const href = relative(from, path);
  return html ? '<a href="' + href + '">' + label + '</a>' : '[' + label + '](' + href + ')';
}

